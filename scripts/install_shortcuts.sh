#!/bin/sh
# Install the short `spice` command (an alias of `spiceharness`) that works from any directory.
#
#   scripts/install_shortcuts.sh [--workspace DIR] [--bin-dir DIR] [--uninstall]
#
# Writes a tiny wrapper (default ~/.local/bin/spice) that runs this checkout's
# .venv Python with absolute paths, Homebrew on PATH for ngspice, and the install-time
# default workspace in SPICEHARNESS_DEFAULT_WORKSPACE (never overriding an existing value).
# Idempotent. Refuses to overwrite any file that is not a SpiceHarness wrapper.
set -eu
SPICEHARNESS_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
MARKER='# spiceharness-shortcut'
BIN_DIR="${HOME}/.local/bin"
WORKSPACE="$SPICEHARNESS_ROOT"
UNINSTALL=0

while [ $# -gt 0 ]; do
    case "$1" in
        --workspace) [ $# -ge 2 ] || { echo "--workspace needs a directory" >&2; exit 2; }; WORKSPACE=$2; shift 2 ;;
        --bin-dir) [ $# -ge 2 ] || { echo "--bin-dir needs a directory" >&2; exit 2; }; BIN_DIR=$2; shift 2 ;;
        --uninstall) UNINSTALL=1; shift ;;
        -h|--help) sed -n '2,10p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
done

TARGET="$BIN_DIR/spice"
is_ours() { [ -f "$1" ] && [ ! -L "$1" ] && head -c 4096 "$1" | grep -q "^$MARKER"; }

if [ "$UNINSTALL" = 1 ]; then
    if [ ! -e "$TARGET" ] && [ ! -L "$TARGET" ]; then echo "Nothing to remove: $TARGET does not exist."; exit 0; fi
    if is_ours "$TARGET"; then rm -- "$TARGET"; echo "Removed $TARGET"; exit 0; fi
    echo "Refusing to remove $TARGET: it is not a SpiceHarness wrapper." >&2; exit 1
fi

if [ ! -x "$SPICEHARNESS_ROOT/.venv/bin/python" ]; then
    echo "SpiceHarness environment missing. Run: cd '$SPICEHARNESS_ROOT' && uv sync --python 3.13" >&2
    exit 1
fi
[ -d "$WORKSPACE" ] || { echo "Workspace directory does not exist: $WORKSPACE" >&2; exit 1; }
WORKSPACE=$(CDPATH= cd -- "$WORKSPACE" && pwd)

if [ -e "$TARGET" ] || [ -L "$TARGET" ]; then
    if ! is_ours "$TARGET"; then
        echo "Refusing to overwrite $TARGET: it is not a SpiceHarness wrapper (no '$MARKER' line)." >&2
        echo "Move it aside or pass --bin-dir DIR to install elsewhere." >&2
        exit 1
    fi
fi

# Single-quote a value for safe embedding in the wrapper.
quote() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }

mkdir -p -- "$BIN_DIR"
TMP=$(mktemp "$BIN_DIR/.spice.XXXXXX")
trap 'rm -f -- "$TMP"' EXIT
{
    printf '#!/bin/sh\n%s\n' "$MARKER"
    printf '# Generated by %s/scripts/install_shortcuts.sh; rerun it to update.\n' "$SPICEHARNESS_ROOT"
    printf 'PATH="/opt/homebrew/bin:/usr/local/bin:${PATH:-/usr/bin:/bin}"\nexport PATH\n'
    printf ': "${SPICEHARNESS_DEFAULT_WORKSPACE:=%s}"\nexport SPICEHARNESS_DEFAULT_WORKSPACE\n' "$(printf '%s' "$WORKSPACE" | sed 's/[\\"$`]/\\&/g')"
    printf 'exec %s -m spiceharness "$@"\n' "$(quote "$SPICEHARNESS_ROOT/.venv/bin/python")"
} > "$TMP"
chmod 755 "$TMP"

if [ -f "$TARGET" ] && cmp -s "$TMP" "$TARGET"; then
    ACTION="already up to date"
elif [ -e "$TARGET" ]; then
    mv -f -- "$TMP" "$TARGET"; ACTION="updated"
else
    mv -f -- "$TMP" "$TARGET"; ACTION="created"
fi
trap - EXIT; rm -f -- "$TMP"

echo "spice shortcut $ACTION: $TARGET"
echo "  runs:              $SPICEHARNESS_ROOT/.venv/bin/python -m spiceharness"
echo "  default workspace: $WORKSPACE (override with -w or SPICEHARNESS_WORKSPACE)"
case ":${PATH:-}:" in
    *":$BIN_DIR:"*) echo "  try: spice runs" ;;
    *) echo "  $BIN_DIR is not on PATH; add: export PATH=\"$BIN_DIR:\$PATH\"" ;;
esac
